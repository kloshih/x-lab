#!/usr/bin/env bash
# Mint nkey user identities for the secure nats instance.
#
#   nkeys.sh [name...]        default names: lo kit
#
# Seeds go to ./nkeys/<name>.nk (0600, git-ignored) — the layout the
# kit's nkeys-dir:// AuthStore reads. Public keys go to ./nkeys.conf
# (tracked). Existing seeds are kept, so re-running only adds names.
# Needs `nk` (nats-io/nkeys) on PATH.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
seeds="$here/nkeys"
names=("$@")
[ ${#names[@]} -gt 0 ] || names=(lo kit)

export PATH="$HOME/.local/bin:$PATH"
command -v nk >/dev/null || { echo "nkeys.sh: nk not on PATH" >&2; exit 1; }
umask 077
mkdir -p "$seeds"

# Keep every already-minted seed in the config, plus any new names.
for f in "$seeds"/*.nk; do
	[ -e "$f" ] || continue
	n="$(basename "$f" .nk)"
	case " ${names[*]} " in *" $n "*) ;; *) names+=("$n") ;; esac
done

{
	echo "# Generated by nkeys.sh — public keys only. Re-run to add a name."
	echo "authorization {"
	echo "    users: ["
	for n in "${names[@]}"; do
		f="$seeds/$n.nk"
		[ -s "$f" ] || nk -gen user >"$f"
		pub="$(nk -inkey "$f" -pubout)"
		echo "        { nkey: $pub, permissions: { publish: \">\", subscribe: \">\" } }  # $n"
	done
	echo "    ]"
	echo "}"
} >"$here/nkeys.conf"
echo "wrote $here/nkeys.conf (seeds in $seeds)"
